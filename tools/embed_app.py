"""Embed Myne's small built-in web files as C string literals."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
lines = ["/* Generated by tools/embed_app.py. */"]
for name, path in (("myne_style", "assets/style.css"),
                   ("myne_runtime", "assets/runtime.js")):
    text = (root / path).read_text()
    lines.append(f"static const char {name}[] = {json.dumps(text)};")
(root / "src/app_assets.inc").write_text("\n".join(lines) + "\n")
